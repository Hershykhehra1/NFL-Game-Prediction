/**
 * Intelligent helper to resolve a stat definition by key, category, and label.
 */
export const getStatDefinition = (key, category = '', label = '') => {
  if (category && STAT_DEFINITIONS[`${category}:${key}`]) {
    return STAT_DEFINITIONS[`${category}:${key}`];
  }
  if (STAT_DEFINITIONS[key]) {
    return STAT_DEFINITIONS[key];
  }
  // Try matching by abbr / label across all definitions
  const targetLabel = (label || key || '').toUpperCase();
  const match = Object.values(STAT_DEFINITIONS).find(
    (d) => d.abbr.toUpperCase() === targetLabel
  );
  if (match) return match;

  return {
    abbr: label || key?.toUpperCase() || 'STAT',
    name: label || key || 'Statistic',
    category: category ? category.charAt(0).toUpperCase() + category.slice(1) : 'Statistic',
    description: 'Statistical performance metric recorded during the matchup.',
    formula: null,
  };
};

